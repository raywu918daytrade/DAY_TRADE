# ── Triple Barrier 參數（標籤怎麼定義，沿用 rally 的定義） ──────────────────
# 2026-07-11 測過改成 2%：test_days=10 AUC 幾乎沒變（0.4925→0.4916），
# test_days=5 有改善（0.5328→0.5732），但樣本量太小（430~1039筆測試）撐不住
# 明確結論，改回 3%。
TP_PCT = 0.03
